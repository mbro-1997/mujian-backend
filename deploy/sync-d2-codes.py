#!/usr/bin/env python3
"""Generate Java stable codes from the approved bundled OpenAPI; --check is read-only."""
import argparse, json, re, sys
from pathlib import Path
root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
source=root/'src/main/resources/contracts/d2a.openapi.json'
j=json.loads(source.read_text());values=set()
def visit(n):
 if isinstance(n,dict):
  values.update(x for x in n.get('enum',[]) if isinstance(x,str))
  if isinstance(n.get('const'),str):values.add(n['const'])
  for v in n.values():visit(v)
 elif isinstance(n,list):
  for v in n:visit(v)
visit(j['components']['schemas'])
def name(v):return 'CODE_'+re.sub('[^A-Za-z0-9]+','_',v).upper()
assert len({name(v) for v in values})==len(values)
content='package com.mujian.backend.common.support;\n\n/** Generated by deploy/sync-d2-codes.py from d2a.openapi.json. Do not edit by hand. */\npublic final class D2Codes {\n  private D2Codes() {}\n\n'+''.join('  public static final String '+name(v)+' = '+json.dumps(v)+';\n' for v in sorted(values))+'}\n'
output=root/'src/main/java/com/mujian/backend/common/support/D2Codes.java'
if args.check:
 if not output.exists() or output.read_text()!=content:sys.exit('D2 Java codes differ: run deploy/sync-d2-codes.py')
else:output.write_text(content)
# Both transport validators use the same approved contract, rather than separate enum registries.
copies=[root.parent/'mujian-frontend/admin-web/src/api/d2a.contract.json',root.parents[1]/'开发交接/D2-准入与道具可租/契约/C-D2-A用户账号与认证.openapi.json']
for copy in copies:
 if json.loads(copy.read_text())!=j:sys.exit('Contract copy differs: '+str(copy))
print('D2 stable string codes:',len(values),'; contract copies match; Java explicit codes, never ordinal')
