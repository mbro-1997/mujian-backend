CREATE TABLE sys_user (
  `id` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '用户 ID',
  `nickname` VARCHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci NOT NULL COMMENT '昵称',
  `avatar_url` VARCHAR(500) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci NULL DEFAULT NULL COMMENT '头像',
  `phone` VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL COMMENT '当前主手机号',
  `phone_verified` TINYINT NOT NULL DEFAULT 0 COMMENT '手机号是否已验证',
  `phone_source` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL COMMENT '手机号来源',
  `phone_verified_at` DATETIME(3) NULL DEFAULT NULL COMMENT '手机号验证时间',
  `user_status` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '用户状态',
  `register_status` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '注册/进入状态',
  `created_at` DATETIME(3) NOT NULL COMMENT '创建时间',
  `updated_at` DATETIME(3) NOT NULL COMMENT '更新时间',
  PRIMARY KEY (id),
  KEY idx_sys_user_phone (phone),
  KEY idx_sys_user_status (user_status,register_status),
  CONSTRAINT ck_sys_user_1 CHECK (REGEXP_LIKE(id, '^[0-9a-f]{12}4[0-9a-f]{3}[89ab][0-9a-f]{15}$','c')),
  CONSTRAINT ck_sys_user_2 CHECK (CHAR_LENGTH(TRIM(nickname))>0),
  CONSTRAINT ck_sys_user_3 CHECK (phone_verified IN (0,1)),
  CONSTRAINT ck_sys_user_4 CHECK (user_status IN ('active','disabled','locked')),
  CONSTRAINT ck_sys_user_5 CHECK (register_status IN ('new','demander_bound','factory_invite_locked','factory_pending','factory_rejected','factory_bound')),
  CONSTRAINT ck_sys_user_6 CHECK ((phone_verified=0 AND phone IS NULL AND phone_source IS NULL AND phone_verified_at IS NULL) OR (phone_verified=1 AND phone IS NOT NULL AND phone_source IS NOT NULL AND phone_verified_at IS NOT NULL AND phone_source IN ('wechat_get_phone_number','sms_otp') AND REGEXP_LIKE(phone, '^\\+?[0-9]{5,19}$','c')))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE sys_user_role (
  `id` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '角色绑定 ID',
  `user_id` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '用户 ID',
  `role_code` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '角色编码',
  `enabled` TINYINT NOT NULL DEFAULT 0 COMMENT '是否启用',
  `enabled_user_guard` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin GENERATED ALWAYS AS (CASE WHEN enabled=1 THEN user_id ELSE NULL END) STORED COMMENT '有效正式身份唯一守卫',
  `created_at` DATETIME(3) NOT NULL COMMENT '创建时间',
  `updated_at` DATETIME(3) NOT NULL COMMENT '更新时间',
  PRIMARY KEY (id),
  UNIQUE KEY uk_user_role (user_id,role_code),
  UNIQUE KEY uk_user_enabled_role (enabled_user_guard),
  CONSTRAINT ck_sys_user_role_1 CHECK (REGEXP_LIKE(id, '^[0-9a-f]{12}4[0-9a-f]{3}[89ab][0-9a-f]{15}$','c')),
  CONSTRAINT ck_sys_user_role_2 CHECK (REGEXP_LIKE(user_id, '^[0-9a-f]{12}4[0-9a-f]{3}[89ab][0-9a-f]{15}$','c')),
  CONSTRAINT ck_sys_user_role_3 CHECK (enabled IN (0,1)),
  CONSTRAINT ck_sys_user_role_4 CHECK (role_code IN ('demander','supplier','admin')),
  CONSTRAINT fk_sys_user_role_1 FOREIGN KEY (user_id) REFERENCES sys_user(id) ON UPDATE RESTRICT ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

