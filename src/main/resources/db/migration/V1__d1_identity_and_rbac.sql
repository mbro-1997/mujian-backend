CREATE TABLE admin_menu (
  `id` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '主键',
  `parent_id` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL COMMENT '父菜单ID',
  `menu_name` VARCHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci NOT NULL COMMENT '菜单名称',
  `menu_type` VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '节点类型',
  `permission_code` VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL COMMENT '权限编码',
  `route_path` VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL COMMENT '前端路由',
  `component_path` VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL COMMENT '组件白名单键',
  `icon_name` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL COMMENT '图标名',
  `visible` TINYINT NOT NULL DEFAULT 0 COMMENT '导航可见标志',
  `enabled` TINYINT NOT NULL DEFAULT 0 COMMENT '启用标志',
  `sort_no` INT NOT NULL DEFAULT 0 COMMENT '同级排序',
  `created_at` DATETIME(3) NOT NULL COMMENT '创建时间',
  `updated_at` DATETIME(3) NOT NULL COMMENT '更新时间',
  PRIMARY KEY (id),
  UNIQUE KEY uk_admin_menu_permission (permission_code),
  KEY idx_admin_menu_tree (parent_id,sort_no),
  KEY idx_admin_menu_route (route_path),
  CONSTRAINT ck_admin_menu_1 CHECK (REGEXP_LIKE(id, '^[0-9a-f]{12}4[0-9a-f]{3}[89ab][0-9a-f]{15}$','c')),
  CONSTRAINT ck_admin_menu_2 CHECK (parent_id IS NULL OR REGEXP_LIKE(parent_id, '^[0-9a-f]{12}4[0-9a-f]{3}[89ab][0-9a-f]{15}$','c')),
  CONSTRAINT ck_admin_menu_3 CHECK (CHAR_LENGTH(TRIM(menu_name))>0),
  CONSTRAINT ck_admin_menu_4 CHECK (visible IN (0,1)),
  CONSTRAINT ck_admin_menu_5 CHECK (enabled IN (0,1)),
  CONSTRAINT ck_admin_menu_6 CHECK (sort_no>=0),
  CONSTRAINT ck_admin_menu_7 CHECK (menu_type IN ('directory','menu','button')),
  CONSTRAINT ck_admin_menu_8 CHECK (parent_id IS NULL OR parent_id <> id),
  CONSTRAINT ck_admin_menu_9 CHECK (permission_code IS NULL OR REGEXP_LIKE(permission_code, '^admin:[a-z0-9-]+:[a-z0-9-]+$','c')),
  CONSTRAINT ck_admin_menu_10 CHECK (menu_type <> 'button' OR (permission_code IS NOT NULL AND route_path IS NULL AND component_path IS NULL)),
  CONSTRAINT ck_admin_menu_11 CHECK (menu_type <> 'directory' OR component_path IS NULL),
  CONSTRAINT ck_admin_menu_12 CHECK (menu_type <> 'menu' OR (route_path IS NOT NULL AND component_path IS NOT NULL AND route_path='/system/menus' AND component_path='system/MenuReadOnly')),
  CONSTRAINT fk_admin_menu_1 FOREIGN KEY (parent_id) REFERENCES admin_menu(id) ON UPDATE RESTRICT ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

