CREATE TABLE `scheme` (
  `id` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '方案 ID',
  `owner_user_id` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '创建人用户 ID',
  `scheme_name` VARCHAR(128) NOT NULL COMMENT '方案名称',
  `description` VARCHAR(1000) NULL DEFAULT NULL COMMENT '方案简介',
  `scheme_status` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '方案状态',
  `active_slot_no` TINYINT NULL DEFAULT NULL COMMENT '未归档名额槽位',
  `content_version` INT NOT NULL DEFAULT 1 COMMENT '内容版本号',
  `version` INT NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
  `share_enabled` TINYINT NOT NULL DEFAULT 1 COMMENT '是否允许分享',
  `archived_at` DATETIME(3) NULL DEFAULT NULL COMMENT '归档时间',
  `created_at` DATETIME(3) NOT NULL COMMENT '创建时间',
  `updated_at` DATETIME(3) NOT NULL COMMENT '更新时间',
  PRIMARY KEY(id),
  UNIQUE KEY a_scheme_slot(owner_user_id,active_slot_no),
  KEY a_scheme_owner(owner_user_id,scheme_status,updated_at,id),
  CONSTRAINT ck_d3a_1_1 CHECK (COALESCE((scheme_status IN ('editing','archived')),FALSE)=TRUE),
  CONSTRAINT ck_d3a_1_2 CHECK (COALESCE(((scheme_status='editing' AND active_slot_no BETWEEN 1 AND 10 AND archived_at IS NULL) OR (scheme_status='archived' AND active_slot_no IS NULL AND archived_at IS NOT NULL)),FALSE)=TRUE),
  CONSTRAINT ck_d3a_1_3 CHECK (COALESCE((content_version>=1 AND version>=0 AND share_enabled IN (0,1)),FALSE)=TRUE),
  CONSTRAINT ck_d3a_1_4 CHECK (COALESCE((id IS NULL OR REGEXP_LIKE(id,'^[0-9a-f]{12}4[0-9a-f]{3}[89ab][0-9a-f]{15}$','c')),FALSE)=TRUE),
  CONSTRAINT ck_d3a_1_5 CHECK (COALESCE((owner_user_id IS NULL OR REGEXP_LIKE(owner_user_id,'^[0-9a-f]{12}4[0-9a-f]{3}[89ab][0-9a-f]{15}$','c')),FALSE)=TRUE),
  CONSTRAINT fk_d3a_1_1 FOREIGN KEY (owner_user_id) REFERENCES sys_user(id) ON DELETE RESTRICT ON UPDATE RESTRICT
